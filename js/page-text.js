const pageTextOriginal = new WeakMap();
let pageTitleEn = null;

function renderPageText(lang) {
  if (typeof document === 'undefined' || !document.body || !document.createTreeWalker) return;
  const bn = lang === 'bn';
  const swap = (en) => {
    const key = en.replace(/\s+/g, ' ').trim();
    const t = bn ? PAGE_TEXT_BN[key] : undefined;
    return t ? en.match(/^\s*/)[0] + t + en.match(/\s*$/)[0] : en;
  };
  if (pageTitleEn === null) pageTitleEn = document.title;
  document.title = swap(pageTitleEn);
  // Skip scripts, styles and anything already bilingual (elements inside body with a lang attribute; <html lang> is not one).
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.parentElement && n.parentElement.closest('script,style,body [lang]') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const en = pageTextOriginal.has(n) ? pageTextOriginal.get(n) : n.nodeValue;
    const out = swap(en);
    if (out !== en) pageTextOriginal.set(n, en);
    if (n.nodeValue !== out) n.nodeValue = out;
  }
}
